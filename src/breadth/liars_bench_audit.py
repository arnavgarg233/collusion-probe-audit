"""Liars' Bench deception - confound audit (RunPod, self-contained, paste-and-go).

Liars' Bench (Cadenza-Labs, arXiv:2511.16035, HF: Cadenza-Labs/liars-bench) is a lie-detection
testbed: 72,863 on-policy examples across 7 sub-datasets + an Alpaca control, generated by 4 open
instruction models. The lie is EXECUTED in the assistant's visible output (the model states
something it believes false), so our law predicts CONFOUNDED: a cheap text baseline over the SAME
visible assistant text should match any layer-20 activation probe, and the text-controlled delta
should fall within its model-grouped permutation null.

The benchmark authors' own white-box probe reads "hidden activations from each response token at
the 20th-percentile layer" (logistic regression, L2). We reproduce a last-token variant at that
layer and put it head-to-head against the visible text under the access-fairness rule (the visible
baseline sees the exact same assistant text the probe pools over).

Two-step:
  python liars_bench_audit.py --inspect                 # download + print the data schema (run FIRST)
  python liars_bench_audit.py --run --model mistralai/Mistral-Small-24B-Instruct-2501 --layer 20

Audit is PER SUB-DATASET (each is a distinct lie type and is treated as a held-out test set by the
authors). The 8 configs are:
  alpaca (control, 0 lies), convincing-game, gender-secret, harm-pressure-choice,
  harm-pressure-knowledge-report, insider-trading, instructed-deception, soft-trigger.

Schema (verified via the HF dataset API, 2026-06): each row has
  messages   : list[{"role": str, "content": str}]  (ChatML; final message is the assistant)
  deceptive  : bool   (True = lie)            # paper text also calls this 'is_lie' -> handled
  model      : str    (which LLM generated it)
  + index, temperature, meta, canary
The PARSE_* picks below are best-effort against that schema; after --inspect, confirm the field
names (it's a one-spot edit, marked >>> ADJUST).
"""
import argparse, json, os
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.pipeline import make_pipeline
from sklearn.model_selection import GroupKFold, cross_val_predict
from sklearn.metrics import roc_auc_score
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA

HF_DATASET = "Cadenza-Labs/liars-bench"
# the 7 lie sub-datasets + the alpaca control (all 'test' split; alpaca also has 'train')
CONFIGS = ["convincing-game", "gender-secret", "harm-pressure-choice",
           "harm-pressure-knowledge-report", "insider-trading", "instructed-deception",
           "soft-trigger", "alpaca"]
# default open assistants the benchmark used (pick ONE per run via --model):
#   mistralai/Mistral-Small-24B-Instruct-2501
#   google/gemma-3-27b-it
#   meta-llama/Llama-3.3-70B-Instruct
#   Qwen/Qwen2.5-72B-Instruct
