def _jsonable(o):
    if isinstance(o, dict):
        return {k: _jsonable(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_jsonable(v) for v in o]
    if isinstance(o, (np.generic,)):
        return o.item()
    return o


# ------------------------------------------------------------------ parsing (>>> ADJUST after inspect)
def _assistant_text(row):
    """Visible behaviour = the assistant's output text. Access-fairness: the text baseline must see
    exactly the tokens the activation probe pools over -> we use the final assistant message
    (the response that is/ isn't a lie). >>> ADJUST: messages field name / role key if --inspect differs."""
    msgs = row.get("messages")
    if isinstance(msgs, list) and msgs:
        # take the last assistant turn; fall back to the very last message
        asst = [m for m in msgs if isinstance(m, dict) and str(m.get("role", "")).lower() == "assistant"]
        m = asst[-1] if asst else msgs[-1]
        if isinstance(m, dict):
            return str(m.get("content") or m.get("text") or m.get("message") or "")
        return str(m)
    # fallbacks for alternative schemas
    return str(row.get("response") or row.get("completion") or row.get("output") or "")


def _full_prompt(row):
    """Full ChatML transcript -> the string we feed the model for activation extraction.
    Last-token activation at --layer is taken over this whole conversation (prompt + response),
    matching how an on-policy probe would see the generated answer in context."""
    msgs = row.get("messages")
    if isinstance(msgs, list) and msgs:
        parts = []
        for m in msgs:
            if isinstance(m, dict):
                parts.append(f"{m.get('role','?')}: {m.get('content') or m.get('text') or ''}")
            else:
                parts.append(str(m))
        return "\n".join(parts)
    return _assistant_text(row)


def _label(row):
    """1 = lie/deceptive, 0 = truthful. >>> ADJUST: paper calls it 'is_lie'; HF card calls it
    'deceptive'. We accept either; alpaca control is all-honest (0)."""
    for k in ("deceptive", "is_lie", "lie", "label"):
        if k in row and row[k] is not None:
            v = row[k]
            if isinstance(v, str):
                return int(v.strip().lower() in ("1", "true", "lie", "deceptive", "yes"))
            return int(bool(v))
    return 0  # alpaca control / unlabeled -> honest


def load_config(cfg, max_rows=None, seed=0):
    """Return (texts, full_prompts, y, groups) for one sub-dataset. groups = generating model
    (the permutation null is grouped by model so the floor respects model-level structure)."""
    from datasets import load_dataset
    ds = load_dataset(HF_DATASET, cfg, split="test")
    if max_rows and len(ds) > max_rows:
        idx = np.random.default_rng(seed).permutation(len(ds))[:max_rows]
        ds = ds.select(sorted(int(i) for i in idx))
    texts, prompts, y, g = [], [], [], []
    for row in ds:
        t = _assistant_text(row)
        if not t:
            continue
        texts.append(t)
        prompts.append(_full_prompt(row))
        y.append(_label(row))
        g.append(str(row.get("model") or row.get("model_name") or "unknown"))
    return texts, prompts, np.array(y, int), np.array(g)


# ------------------------------------------------------------------ extraction (assistant model, layer-20 last token)
def extract(prompts, model_name, layer, max_len=1024, load_8bit=False):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer
    tok = AutoTokenizer.from_pretrained(model_name)
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    kw = dict(device_map="auto")
    if load_8bit:
        from transformers import BitsAndBytesConfig
        kw["quantization_config"] = BitsAndBytesConfig(load_in_8bit=True, llm_int8_skip_modules=["lm_head"])
    else:
        kw["torch_dtype"] = torch.float16
    model = AutoModelForCausalLM.from_pretrained(model_name, **kw).eval()
    out = []
    for i, p in enumerate(prompts):
        ids = tok(p, return_tensors="pt", truncation=True, max_length=max_len).to(model.device)
        with torch.no_grad():
            hs = model(**ids, output_hidden_states=True).hidden_states[layer][0, -1]
        out.append(hs.float().cpu().numpy())
        if i % 200 == 0:
            print(f"  extract {i}/{len(prompts)}", flush=True)
    return np.stack(out)


# ------------------------------------------------------------------ the audit (same protocol as the breadth study)
def _oof(est, X, y, g):
    y = np.asarray(y).astype(int); g = np.asarray(g)
    if len(set(y)) < 2 or len(set(g)) < 2:
        return np.full(len(y), np.nan)
    k = max(2, min(5, len(set(g))))
    return cross_val_predict(est, X, y, cv=GroupKFold(k), groups=g, method="predict_proba")[:, 1]


def _auroc(p, y):
    y = np.asarray(y).astype(int); m = ~np.isnan(p)
    return roc_auc_score(y[m], p[m]) if (m.sum() > 4 and len(set(y[m])) == 2) else float("nan")


def _block_perm(y, g, rng):
    g = np.asarray(g); y = np.asarray(y)
    bg = {gg: y[g == gg] for gg in set(g)}
    if all(len(set(v)) == 1 for v in bg.values()):       # label constant within group -> block permute
        ks = list(bg); perm = rng.permutation([bg[k][0] for k in ks]); mp = dict(zip(ks, perm))
        return np.array([mp[gg] for gg in g])
    return rng.permutation(y)


def audit(X_act, texts, y, groups, n_perm=80, seed=0):
    y = np.asarray(y).astype(int)
    text_clf = lambda: make_pipeline(TfidfVectorizer(ngram_range=(1, 2), min_df=2, max_features=5000, sublinear_tf=True),
                                     LogisticRegression(solver="liblinear", C=1.0, max_iter=5000))
    lr = lambda: LogisticRegression(max_iter=3000, C=0.5, class_weight="balanced")
    Xs = StandardScaler().fit_transform(X_act)
    Apca = PCA(min(30, Xs.shape[1], max(2, Xs.shape[0] - 1))).fit_transform(Xs)
    tpred = _oof(text_clf(), list(texts), y, groups)
    act_auroc = _auroc(_oof(lr(), Apca, y, groups), y)
    text_auroc = _auroc(tpred, y)
    full = np.column_stack([tpred.reshape(-1, 1), Apca])
    full_auroc = _auroc(_oof(lr(), full, y, groups), y)
    delta = full_auroc - text_auroc
    rng = np.random.default_rng(seed); floors = []
    for _ in range(n_perm):
        yp = _block_perm(y, groups, rng)
        v = _auroc(_oof(text_clf(), list(texts), yp, groups), yp)
        f = _auroc(_oof(lr(), np.column_stack([_oof(text_clf(), list(texts), yp, groups).reshape(-1, 1), Apca]), yp, groups), yp)
        if v == v and f == f:
            floors.append(f - v)
    floor95 = float(np.percentile(floors, 95)) if floors else float("nan")
    p = float(np.mean([fl >= delta for fl in floors])) if floors else float("nan")
    verdict = ("WHITE_BOX_WINS" if (delta == delta and delta > floor95 and delta >= 0.10) else
               "CONFOUNDED" if (delta == delta and delta <= floor95) else "PARTIAL")
    return dict(n=int(len(y)), pos=int(y.sum()), act=round(act_auroc, 3), text=round(text_auroc, 3),
                full=round(full_auroc, 3), delta=round(delta, 3), floor95=round(floor95, 3),
                p=round(p, 3), verdict=verdict)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inspect", action="store_true")
    ap.add_argument("--run", action="store_true")
    ap.add_argument("--model", default="mistralai/Mistral-Small-24B-Instruct-2501")
    ap.add_argument("--layer", type=int, default=20)
    ap.add_argument("--configs", default=",".join(CONFIGS),
                    help="comma-sep sub-datasets to audit (default: all 7 lie sets + alpaca)")
    ap.add_argument("--max-rows", type=int, default=1500,
                    help="cap rows per sub-dataset (soft-trigger/instructed-deception are large)")
    ap.add_argument("--n-perm", type=int, default=80)
    ap.add_argument("--load-8bit", action="store_true", help="needed for the 70B/72B assistants")
    ap.add_argument("--out", default="/workspace/liars_bench_result.json")
    a = ap.parse_args()
    if a.inspect or not a.run:
        inspect(); return

    cfgs = [c.strip() for c in a.configs.split(",") if c.strip()]
    results = {"dataset": HF_DATASET, "model": a.model, "layer": a.layer,
               "regime_expected": "CONFOUNDED", "per_config": {}}
    for cfg in cfgs:
        print(f"\n############ sub-dataset: {cfg} ############", flush=True)
        try:
            texts, prompts, y, g = load_config(cfg, max_rows=a.max_rows)
        except Exception as e:
            print(f"  load err for {cfg}: {e}"); results["per_config"][cfg] = {"error": str(e)}; continue
        print(f"  rows={len(y)} lies={int(y.sum())} models={sorted(set(g))}")
        if len(y) < 50:
            print("  too few rows -> skip"); results["per_config"][cfg] = {"skipped": "n<50", "n": int(len(y))}; continue
        if len(set(y)) < 2:
            print("  single-class (e.g. alpaca control all-honest) -> activation/text AUROC undefined; "
                  "reporting n only")
            results["per_config"][cfg] = {"n": int(len(y)), "pos": int(y.sum()),
                                          "note": "single-class control; no AUROC"}
            continue
        X = extract(prompts, a.model, a.layer, load_8bit=a.load_8bit)
        res = audit(X, texts, y, g, n_perm=a.n_perm)
        print(f"  {cfg}: {res}", flush=True)
        results["per_config"][cfg] = res
        json.dump(results, open(a.out, "w"), indent=2)  # checkpoint after each sub-dataset

    print("\n=== LIARS' BENCH AUDIT ===")
    print(json.dumps(results, indent=2))
    verdicts = [v.get("verdict") for v in results["per_config"].values() if isinstance(v, dict) and "verdict" in v]
    print(f"\nExpected: CONFOUNDED everywhere (the lie executes in the visible assistant text). "
          f"verdicts={verdicts}")
    json.dump(results, open(a.out, "w"), indent=2)


if __name__ == "__main__":
    main()
